#!/usr/bin/env python3
"""Write the reth benchmarkoor configs. usage: mkcfg.py <image@digest> [filter]
J-prerun: jochemnet as published, pre-run replayed once and promoted (smoke filter).
J/S: the baseline arms, no pre-run block (the J virgin already holds it); run ids come from the CLI."""
import sys
import os
IMG = sys.argv[1]
FILTER = sys.argv[2] if len(sys.argv) > 2 else "regex:(160M|240M)"
JOC_FX = ("https://github.com/ethpandaops/benchmarkoor-tests/releases/download/"
          "eest-payloads-jochemnet-v1-amsterdam-stateful-d9ad55b3-20260807-000744/"
          "eest-payloads-jochemnet-v1-amsterdam-stateful-geth.tar.gz")
# S fixtures must be filled on the genesis of the S store in use: the reth fill of the cycle-2 store
# (the cycle-1 nethermind fill went with its stores). S_FX overrides.
S_FX = os.environ.get("S_FX", "/data/fixtures/sa-h-reth")
def cfg(rid, arm, filt, prerun=False):
    if arm == "J":
        src = f"""          fixtures_url: {JOC_FX}
          fixtures_subdir: benchmarkoor-build-artifacts/eest-payloads/geth/blockchain_tests_stateful_engine"""
        if prerun:
            src += "\n          pre_runs:\n            fixtures_subdir: benchmarkoor-build-artifacts/pre-runs/geth/pre_run_bundle"
        dd, gen, fo, block = "/schelk-joc/reth", "/root/bench/besu-mainnet-genesis.json", "{ amsterdam: 1769856769 }", "24402727"
    else:
        src = f"""          local_fixtures_dir: {S_FX}
          fixtures_subdir: blockchain_tests_stateful_engine"""
        dd, gen, fo, block = "/schelk-sa/reth", "/schelk-sa/reth/chainspec.json", "{ amsterdam: 1 }", "0"
    schelk_opts = "\n        schelk_options:\n          promote_post_pre_runs: true" if prerun else ""
    return f"""# reth state-DB study, run {rid} ({'jochemnet' if arm == 'J' else 'state-actor'} arm). Generated by mkcfg.py.
# scratch on md2 NVMe (measured reads), virgin on md3 HDD (restores); benchmarkoor default reth command.
global:
  log_level: info
runner:
  client_logs_to_stdout: true
  docker_network: benchmarkoor
  cleanup_on_start: true
  container_runtime: podman
  live_reporting:
    enabled: false
  benchmark:
    results_dir: /root/bench/reth/results/{rid}
    generate_results_index: true
    generate_suite_stats: true
    tests:
      metadata:
        labels:
          name: reth-{rid}-glamsterdam-stateful
          block: "{block}"
          test-type: stateful
          context: repricing
          fork: amsterdam
          data-disk-type: schelk
      filter: '{filt}'
      source:
        eest_fixtures:
{src}
  client:
    config:
      rollback_strategy: container-recreate
      drop_memory_caches: "steps"
    datadirs:
      reth:
        source_dir: {dd}
        method: schelk{schelk_opts}
  instances:
    - id: reth-{rid}
      client: reth
      image: {IMG}
      pull_policy: never
      genesis: {gen}
      genesis_fork_override: {fo}
"""
open("/root/bench/reth/cfg/J-prerun.yaml", "w").write(cfg("j-prerun", "J", sys.argv[3] if len(sys.argv) > 3 else "regex:(BALANCE.*EXISTING_EOA.*overhead_baseline_False.*160M)", prerun=True))
for r in ("J1", "J2", "J-smoke"): open(f"/root/bench/reth/cfg/{r}.yaml", "w").write(cfg(r.lower(), "J", FILTER))
for r in ("S1", "S2", "S-smoke"): open(f"/root/bench/reth/cfg/{r}.yaml", "w").write(cfg(r.lower(), "S", FILTER))
print("wrote", IMG, FILTER)
